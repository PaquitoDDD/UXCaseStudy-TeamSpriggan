function GranoMolido() {
  const [isHovered, setIsHovered] = useState(false);
  const [isOpen, setIsOpen] = useState(false);
  const [selectedOption, setSelectedOption] = useState('Grano');
  const dropdownRef = useRef<HTMLDivElement>(null);

  const options = [
    'Grano',
    'Molido AeroPress',
    'Molido V60',
    'Molido Chemex',
    'Molido Espresso',
    'Molido Moka Italiana',
    'Molido Prensa Francesa',
  ];

  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (dropdownRef.current && !dropdownRef.current.contains(event.target as Node)) {
        setIsOpen(false);
      }
    };

    if (isOpen) {
      document.addEventListener('mousedown', handleClickOutside);
    }

    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
    };
  }, [isOpen]);

  return (
    <div ref={dropdownRef} className="relative w-full" data-name="Grano - Molido">
      <div
        className="bg-white min-w-[68px] relative shrink-0 w-full cursor-pointer transition-all duration-200"
        onMouseEnter={() => setIsHovered(true)}
        onMouseLeave={() => setIsHovered(false)}
        onClick={() => setIsOpen(!isOpen)}
        style={{
          backgroundColor: isHovered ? '#f5f5f5' : 'white',
        }}
      >
        <div aria-hidden="true" className="absolute border border-[rgba(0,0,0,0.6)] border-solid inset-0 pointer-events-none" />
        <div className="flex flex-row items-center min-w-[inherit] size-full">
          <div className="content-stretch flex items-center min-w-[inherit] pl-[12.8px] pr-[7.8px] py-[8.8px] relative size-full">
            <SpanS8RjWNe2 selectedOption={selectedOption} />
            <SpanShVte1E />
          </div>
        </div>
      </div>

      {isOpen && (
        <div className="absolute top-full left-0 w-full bg-white border border-[rgba(0,0,0,0.6)] mt-1 z-50 max-h-[300px] overflow-y-auto shadow-lg">
          {options.map((option, index) => (
            <div
              key={index}
              className="px-[12.8px] py-[8.8px] cursor-pointer hover:bg-[#f5f5f5] transition-colors duration-200"
              onClick={(e) => {
                e.stopPropagation();
                setSelectedOption(option);
                setIsOpen(false);
              }}
            >
              <p className="font-['helvetica-w01-roman:Regular',sans-serif] text-[15px] text-[#444] leading-[21px]">
                {option}
              </p>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}

